# Значки вкладки, ярлыков и веб-приложения + логотип BrandLogo — одна эмблема
# «корона с горами» на прозрачном фоне. Источник: public/brand/emblem-master.png
# (его готовит scripts/build-menu-emblem.py). Запуск: python3 scripts/build-app-icons.py
import hashlib, json, re, struct
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / 'public'
MASTER = PUBLIC / 'brand' / 'emblem-master.png'
data = MASTER.read_bytes()
revision = hashlib.sha256(data).hexdigest()[:12]
rel = f'brand/emblem-{revision}/'
out = PUBLIC / rel
out.mkdir(parents=True, exist_ok=True)
master = Image.open(BytesIO(data)).convert('RGBA')

def render(size, pad=0.0):
  """Эмблема по центру квадрата size×size; pad — доля пустого поля с каждой стороны."""
  inner = max(1, round(size * (1 - 2 * pad)))
  em = master.resize((inner, inner), Image.LANCZOS)
  if size <= 48:  # мелкие значки — чуть резче
    em = em.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=0))
  canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
  canvas.alpha_composite(em, ((size - inner) // 2, (size - inner) // 2))
  return canvas

files = {
  'favicon-16x16.png': render(16), 'favicon-32x32.png': render(32), 'favicon-48x48.png': render(48),
  'logo-96.png': render(96), 'logo-256.png': render(256),
  'apple-touch-icon.png': render(180, 0.04),
  'icon-192.png': render(192), 'icon-512.png': render(512),
  # Maskable: вся эмблема внутри центральной безопасной окружности (80 %).
  'icon-maskable-512.png': render(512, 0.14),
}
pngs = {}
for name, img in files.items():
  buf = BytesIO(); img.save(buf, 'PNG', optimize=True); pngs[name] = buf.getvalue()
  (out / name).write_bytes(pngs[name])
  # Старые ярлыки ещё обращаются к прежним адресам в корне.
  (PUBLIC / name).write_bytes(pngs[name])

sizes = [16, 32, 48]
blobs = [pngs[f'favicon-{s}x{s}.png'] for s in sizes]
head = struct.pack('<HHH', 0, 1, len(sizes))
offset = 6 + 16 * len(sizes)
for s, b in zip(sizes, blobs):
  head += struct.pack('<BBBBHHII', s, s, 0, 0, 1, 32, len(b), offset); offset += len(b)
ico = head + b''.join(blobs)
(out / 'favicon.ico').write_bytes(ico); (PUBLIC / 'favicon.ico').write_bytes(ico)

(ROOT / 'src' / 'brandAssets.ts').write_text(
  f"// Generated by scripts/build-app-icons.py from public/brand/emblem-master.png.\nexport const BRAND_ASSET_ROOT = '{rel}';\n")
mp = PUBLIC / 'manifest.webmanifest'
manifest = json.loads(mp.read_text())
manifest['icons'] = [{**i, 'src': rel + i['src'].split('/')[-1].split('?')[0]} for i in manifest['icons']]
mp.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
ip = ROOT / 'index.html'
html = ip.read_text()
html = re.sub(r'%BASE_URL%(?:brand/[^"\s]+/)?(favicon[^"?\s]*|apple-touch-icon\.png|icon-192\.png)(?:\?[^"\s]*)?', lambda m: f'%BASE_URL%{rel}{m.group(1)}', html)
html = re.sub(r'%BASE_URL%manifest\.webmanifest(?:\?[^"\s]*)?', f'%BASE_URL%manifest.webmanifest?v={revision}', html)
ip.write_text(html)
print(f'Значки: public/{rel}')
