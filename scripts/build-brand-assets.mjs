/* global Buffer, process, console, Image, document */
import { chromium } from 'playwright';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

// Resample the supplied artwork without redrawing, recolouring or cropping it.
const source = await readFile(new URL('../public/brand/your-life-source.jpg', import.meta.url));
const revision = createHash('sha256').update(source).digest('hex').slice(0, 12);
const root = `brand/your-life-${revision}/`;
const publicDir = new URL('../public/', import.meta.url);
const output = new URL(root, publicDir);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({
  executablePath: process.env.LIFEGAME_CHROMIUM_PATH || undefined,
  args: ['--no-sandbox'],
});
const images = new Map();
try {
  const page = await browser.newPage();
  for (const [name, size, maskable] of [
    ['favicon-16x16.png', 16], ['favicon-32x32.png', 32], ['favicon-48x48.png', 48],
    ['logo-96.png', 96], ['logo-256.png', 256], ['apple-touch-icon.png', 180],
    ['icon-192.png', 192], ['icon-512.png', 512], ['icon-maskable-512.png', 512, true],
  ]) {
    const png = await page.evaluate(async ({ image, size, maskable }) => {
      const photo = new Image();
      photo.src = image;
      await photo.decode();
      const canvas = document.createElement('canvas');
      canvas.width = canvas.height = size;
      const context = canvas.getContext('2d');
      context.fillStyle = '#ffffff';
      context.fillRect(0, 0, size, size);
      context.imageSmoothingEnabled = true;
      context.imageSmoothingQuality = 'high';
      // A maskable icon's artwork fits entirely inside its central safe circle.
      const scale = Math.min(size / photo.naturalWidth, size / photo.naturalHeight) * (maskable ? 0.55 : 1);
      const width = photo.naturalWidth * scale, height = photo.naturalHeight * scale;
      context.drawImage(photo, (size - width) / 2, (size - height) / 2, width, height);
      return canvas.toDataURL('image/png').split(',')[1];
    }, { image: `data:image/jpeg;base64,${source.toString('base64')}`, size, maskable });
    const bytes = Buffer.from(png, 'base64');
    images.set(size, bytes);
    await writeFile(new URL(name, output), bytes);
    // Existing installed shortcuts may still request these original URLs.
    await copyFile(new URL(name, output), new URL(name, publicDir));
  }
} finally {
  await browser.close();
}

const sizes = [16, 32, 48];
const header = Buffer.alloc(6 + sizes.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
for (const [index, size] of sizes.entries()) {
  const png = images.get(size), entry = 6 + index * 16;
  header[entry] = header[entry + 1] = size;
  header.writeUInt16LE(1, entry + 4);
  header.writeUInt16LE(32, entry + 6);
  header.writeUInt32LE(png.length, entry + 8);
  header.writeUInt32LE(offset, entry + 12);
  offset += png.length;
}
const ico = Buffer.concat([header, ...sizes.map(size => images.get(size))]);
await writeFile(new URL('favicon.ico', output), ico);
await copyFile(new URL('favicon.ico', output), new URL('favicon.ico', publicDir));
await writeFile(new URL('../src/brandAssets.ts', import.meta.url), `// Generated by scripts/build-brand-assets.mjs from the supplied logo.\nexport const BRAND_ASSET_ROOT = '${root}';\n`);

const manifestPath = new URL('manifest.webmanifest', publicDir);
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.icons = manifest.icons.map(icon => ({ ...icon, src: root + icon.src.split('/').pop().split('?')[0] }));
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
const indexPath = new URL('../index.html', import.meta.url);
const html = (await readFile(indexPath, 'utf8'))
  .replace(/%BASE_URL%(?:brand\/[^"\s]+\/)?(favicon[^"?\s]*|apple-touch-icon\.png|icon-192\.png)(?:\?[^"\s]*)?/g, `%BASE_URL%${root}$1`)
  .replace(/%BASE_URL%manifest\.webmanifest(?:\?[^"\s]*)?/g, `%BASE_URL%manifest.webmanifest?v=${revision}`);
await writeFile(indexPath, html);
console.log(`Brand assets ready: ${root}; full artwork preserved; 16/32/48/96/180/192/256/512 px.`);
